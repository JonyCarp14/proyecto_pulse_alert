-- 1. TABLA USUARIOS

CREATE TABLE IF NOT EXISTS usuarios (
    id_user INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'user',
    plan VARCHAR(20) NOT NULL DEFAULT 'free'
);


-- 2. TABLA CAMPAIGNS

CREATE TABLE IF NOT EXISTS campaigns (
    id_campaign INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    meta_campaign_id VARCHAR(100),
    nombre VARCHAR(150) NOT NULL,
    cuenta_publicitaria VARCHAR(100),
    presupuesto FLOAT NOT NULL,
    gasto FLOAT DEFAULT 0,
    impresiones INTEGER DEFAULT 0,
    clics INTEGER DEFAULT 0,
    resultados INTEGER DEFAULT 0,
    estado VARCHAR(20) DEFAULT 'activa',

    CONSTRAINT fk_campaign_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id_user)
);


-- 3. TABLA ALERTS

CREATE TABLE IF NOT EXISTS alerts (
    id_alert INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    mensaje VARCHAR(255) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    leida BOOLEAN DEFAULT FALSE,
    metrica VARCHAR(50) NOT NULL,
    valor_detectado FLOAT NOT NULL,
    limite FLOAT NOT NULL,
    estado_envio VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    regla_id INTEGER,

    CONSTRAINT fk_alert_campaign
        FOREIGN KEY (campaign_id)
        REFERENCES campaigns(id_campaign)
);


-- 4. TABLA REPORTS

CREATE TABLE IF NOT EXISTS reports (
    id_report INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    channel VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    message_status VARCHAR(20) NOT NULL DEFAULT 'pendiente',

    CONSTRAINT fk_report_campaign
        FOREIGN KEY (campaign_id)
        REFERENCES campaigns(id_campaign)
);


-- 5. TABLA CAMPAIGN_METRICS_HISTORY
-- NUEVA TABLA: HISTORIAL DE METRICAS

CREATE TABLE IF NOT EXISTS campaign_metrics_history (
    id_history INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL,
    fecha DATE NOT NULL,
    clics INTEGER NOT NULL DEFAULT 0,
    impresiones INTEGER NOT NULL DEFAULT 0,
    gasto NUMERIC(12, 2) NOT NULL DEFAULT 0,
    resultados INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_history_campaign
        FOREIGN KEY (campaign_id)
        REFERENCES campaigns(id_campaign)
        ON DELETE CASCADE,

    CONSTRAINT uq_campaign_metrics_date
        UNIQUE (campaign_id, fecha)
);


