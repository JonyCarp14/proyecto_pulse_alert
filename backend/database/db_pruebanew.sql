-- 11. CONSULTAS PARA COMPROBAR LOS DATOS
-- =========================================

-- CONSULTAR USUARIOS

SELECT * FROM usuarios;


-- CONSULTAR CAMPAÑAS

SELECT * FROM campaigns;


-- CONSULTAR HISTORIAL DE METRICAS

SELECT * FROM campaign_metrics_history;


-- CONSULTAR ALERTAS

SELECT * FROM alerts;


-- CONSULTAR REPORTES

SELECT * FROM reports;


-- CONSULTAR CAMPAÑAS JUNTO CON SUS USUARIOS

SELECT
    c.nombre AS campania,
    u.nombre,
    u.apellido,
    u.email,
    u.rol,
    u.plan,
    c.gasto,
    c.resultados,
    c.gasto / NULLIF(c.resultados, 0) AS costo_por_resultado
FROM campaigns c
INNER JOIN usuarios u
    ON c.usuario_id = u.id_user;


-- CONSULTAR ALERTAS JUNTO CON SUS CAMPAÑAS

SELECT
    a.id_alert,
    c.nombre AS campania,
    a.metrica,
    a.valor_detectado,
    a.limite,
    a.mensaje,
    a.estado_envio
FROM alerts a
INNER JOIN campaigns c
    ON a.campaign_id = c.id_campaign;


-- CONSULTAR HISTORIAL DE UNA CAMPAÑA

SELECT
    c.nombre AS campania,
    h.fecha,
    h.clics,
    h.impresiones,
    h.gasto,
    h.resultados
FROM campaign_metrics_history h
INNER JOIN campaigns c
    ON h.campaign_id = c.id_campaign
WHERE c.id_campaign = 1
ORDER BY h.fecha;
