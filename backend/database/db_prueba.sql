-- Consultar usuarios
SELECT * FROM usuarios;

-- Consultar campañas
SELECT * FROM campaigns;

-- Consultar alertas
SELECT * FROM alerts;

-- Consultar reportes
SELECT * FROM reports;

-- Consultar campaña junto con su usuario
SELECT
    c.nombre AS campania,
    u.nombre,
    u.apellido,
    u.email,
    c.gasto,
    c.resultados,
    c.gasto / NULLIF(c.resultados, 0) AS costo_por_resultado
FROM campaigns c
INNER JOIN usuarios u
    ON c.usuario_id = u.id_user;

-- Consultar alertas junto con sus campañas
SELECT
    a.id_alert,
    c.nombre AS campania,
    a.metrica,
    a.valor_detectado,
    a.limite,
    a.mensaje,
    a.estado_envio
FROM alerts a
INNER JOIN campaigns c
    ON a.campaign_id = c.id_campaign;
